$script:Secrets = [System.Collections.Generic.List[string]]::new()
$script:TempPaths = [System.Collections.Generic.List[string]]::new()

function Write-Step([string]$Text) { Write-Host "`n== $Text" }
function Write-Info([string]$Text) { Write-Host "   $Text" }
function Stop-Setup([string]$Text) { throw "ERROR: $Text" }
function Get-Masked([string]$Text) {
    foreach ($s in $script:Secrets) { if ($s) { $Text = $Text.Replace($s, '***') } }
    return $Text
}
function Show-Command([string]$Exe, [string[]]$Arguments) {
    $shown = ($Arguments | ForEach-Object { if ($_ -match '\s') { "`"$_`"" } else { $_ } }) -join ' '
    Write-Host ('   + ' + (Get-Masked "$Exe $shown"))
}
function Invoke-Native([string]$Exe, [string[]]$Arguments, [string]$WorkDir) {
    Show-Command $Exe $Arguments
    if ($DryRun) { return }
    if ($WorkDir) { Push-Location $WorkDir }
    try {
        & $Exe @Arguments
        if ($LASTEXITCODE -ne 0) { Stop-Setup "'$Exe $($Arguments[0])' failed with exit code $LASTEXITCODE." }
    } finally { if ($WorkDir) { Pop-Location } }
}
function Get-NativeOutput([string]$Placeholder, [string]$Exe, [string[]]$Arguments) {
    Show-Command $Exe $Arguments
    if ($DryRun) { return $Placeholder }
    $out = & $Exe @Arguments
    if ($LASTEXITCODE -ne 0) { Stop-Setup "'$Exe $($Arguments[0])' failed with exit code $LASTEXITCODE." }
    return (($out | Out-String).Trim())
}
function Read-JsonFile([string]$Path) {
    if (Test-Path $Path) {
        $raw = Get-Content $Path -Raw
        if ($raw -and $raw.Trim()) { return ($raw | ConvertFrom-Json -AsHashtable) }
    }
    return @{}
}
function Write-JsonFile([string]$Path, [hashtable]$Data) {
    Set-Content -Path $Path -Value ($Data | ConvertTo-Json -Depth 5) -Encoding utf8NoBOM
}
function Get-State([string]$Key) { if ($script:State.ContainsKey($Key)) { return [string]$script:State[$Key] } else { return '' } }
function Set-State([string]$Key, [string]$Value) {
    $script:State[$Key] = $Value
    if (-not $DryRun) { Write-JsonFile $StateFile $script:State }
}
function Set-CdkContext([string]$Key, [string]$Value) {
    Write-Host "   + set `"$Key`": `"$Value`" in infra/Commonroom.Infra/cdk.context.json"
    if ($DryRun) { return }
    $ctx = Read-JsonFile $CdkContext
    $ctx[$Key] = $Value
    Write-JsonFile $CdkContext $ctx
}
# Runs the command only if state KEY is not '1', then sets it.
function Invoke-Once([string]$Key, [string]$Exe, [string[]]$Arguments) {
    if ((Get-State $Key) -eq '1') { Show-Command $Exe $Arguments; Write-Info '  (already done, skipped)'; return }
    Invoke-Native $Exe $Arguments
    Set-State $Key '1'
}
function Get-DotEnvValue([string]$Path, [string]$Key) {
    if (-not (Test-Path $Path)) { return '' }
    $line = Get-Content $Path | Where-Object { $_ -like "$Key=*" } | Select-Object -Last 1
    if ($line) { return $line.Substring($Key.Length + 1).Trim() } else { return '' }
}
function Write-EnvFile([string]$Path, [string[]]$Lines) {
    $rel = [IO.Path]::GetRelativePath($Repo, $Path)
    $content = (@("# Generated by deploy/setup (LEVEL=$($cfg.LEVEL)). Do not commit.") + $Lines) -join "`n"
    Write-Host "   + write $rel"
    foreach ($l in $Lines) { Write-Info ('    ' + (Get-Masked $l)) }
    if ($DryRun) { return }
    if ((Test-Path $Path) -and ((Get-Content $Path -Raw).TrimEnd() -ne $content)) {
        $bak = "$Path.bak-$(Get-Date -Format yyyyMMddHHmmss)"
        Copy-Item $Path $bak
        Write-Info "previous file kept as $([IO.Path]::GetRelativePath($Repo, $bak))"
    }
    Set-Content -Path $Path -Value $content -Encoding utf8NoBOM
    git -C $Repo check-ignore -q $Path
    if ($LASTEXITCODE -ne 0) { Stop-Setup "$rel is not git-ignored: stop before a key is committed." }
}
function New-ZipFile([string]$Source, [string]$Zip) {
    # tar/bsdtar, never Compress-Archive (backslashes in entry names break Linux App Service).
    Write-Host "   + tar -a -c -f $Zip -C $Source ."
    if ($DryRun) { return }
    if ($IsWindows) { $tar = Join-Path $env:SystemRoot 'System32/tar.exe' }
    elseif ((& tar --version 2>$null) -match 'bsdtar') { $tar = 'tar' }
    elseif (Get-Command zip -ErrorAction SilentlyContinue) {
        Push-Location $Source; try { & zip -qr $Zip . } finally { Pop-Location }; return
    }
    else { Stop-Setup 'No zip-capable tool found (bsdtar or zip).' }
    & $tar -a -c -f $Zip -C $Source .
    if ($LASTEXITCODE -ne 0) { Stop-Setup 'zip creation failed.' }
}
function Test-Level([string]$AtLeast) { return $Levels.IndexOf($cfg.LEVEL) -ge $Levels.IndexOf($AtLeast) }
function Assert-Command([string]$Name, [string]$Hint) {
    if (-not (Get-Command $Name -ErrorAction SilentlyContinue)) { Stop-Setup "'$Name' not found: $Hint" }
}
function New-RandomString([int]$Bytes) {
    $buf = [byte[]]::new($Bytes)
    [System.Security.Cryptography.RandomNumberGenerator]::Fill($buf)
    return $buf
}

# ---------------------------------------------------------------- configuration
function Read-Config {
    if (-not (Test-Path $EnvFile)) { Stop-Setup 'deploy/env.local not found: copy deploy/env.example to deploy/env.local, then edit it.' }
    $c = @{ AWS_PROFILE = 'default'; DOCS_DIR = 'samples/docs' }
    $known = 'PREFIX', 'LEVEL', 'AWS_PROFILE', 'AWS_REGION', 'AZ_LOCATION', 'AZ_SWA_LOCATION', 'MODEL_NAME', 'MODEL_VERSION', 'MODEL_SKU', 'DOCS_DIR'
    foreach ($line in Get-Content $EnvFile) {
        $l = ($line -split '#', 2)[0]
        if ($l -match '^\s*([A-Z_][A-Z0-9_]*)\s*=\s*(.*?)\s*$' -and $known -contains $Matches[1] -and $Matches[2]) { $c[$Matches[1]] = $Matches[2] }
    }
    foreach ($k in $known) { if (-not $c.ContainsKey($k)) { $c[$k] = '' } }
    if ($c.PREFIX -cnotmatch '^[a-z][a-z0-9-]{1,14}[a-z0-9]$') { Stop-Setup "PREFIX must be 3-16 chars: lowercase letters, digits, '-'." }
    if ($c.PREFIX -match 'aws|amazon|cognito') { Stop-Setup 'PREFIX must not contain aws, amazon or cognito (Cognito domain rule).' }
    if ($Levels -notcontains $c.LEVEL) { Stop-Setup 'LEVEL must be local-fake, local-foundry or azure.' }
    if (-not $c.AWS_REGION) { Stop-Setup 'AWS_REGION is required.' }
    $lvl = $Levels.IndexOf($c.LEVEL)
    if ($lvl -ge 1) { foreach ($k in 'AZ_LOCATION', 'MODEL_NAME', 'MODEL_VERSION', 'MODEL_SKU') { if (-not $c[$k]) { Stop-Setup "$k is required for LEVEL=$($c.LEVEL)." } } }
    if ($lvl -ge 2 -and -not $c.AZ_SWA_LOCATION) { Stop-Setup 'AZ_SWA_LOCATION is required for LEVEL=azure.' }
    if (-not [IO.Path]::IsPathRooted($c.DOCS_DIR)) { $c.DOCS_DIR = Join-Path $Repo $c.DOCS_DIR }
    $env:AWS_PROFILE = $c.AWS_PROFILE
    $env:AWS_REGION = $c.AWS_REGION
    $env:AWS_DEFAULT_REGION = $c.AWS_REGION
    $env:CDK_DEFAULT_REGION = $c.AWS_REGION
    return $c
}

function Initialize-State {
    $script:State = Read-JsonFile $StateFile
    $saved = Get-State 'prefix'
    if ($saved -and $saved -ne $cfg.PREFIX) { Stop-Setup "deploy/.state.json belongs to PREFIX=${saved}: run deploy/teardown.ps1 first or restore that PREFIX." }
    $suffix = Get-State 'suffix'
    if (-not $suffix) {
        $alphabet = 'abcdefghijklmnopqrstuvwxyz0123456789'
        $suffix = -join (New-RandomString 4 | ForEach-Object { $alphabet[$_ % 36] })
    }
    $script:Names = @{
        Suffix = $suffix; Rg = "rg-$($cfg.PREFIX)-$suffix"; Foundry = "foundry-$($cfg.PREFIX)-$suffix"
        Plan = "plan-$($cfg.PREFIX)-$suffix"; Api = "api-$($cfg.PREFIX)-$suffix"; Swa = "swa-$($cfg.PREFIX)-$suffix"
        DomainPrefix = "$($cfg.PREFIX)-$suffix"
    }
    Set-State 'prefix' $cfg.PREFIX; Set-State 'suffix' $suffix; Set-State 'level' $cfg.LEVEL
    Set-State 'awsProfile' $cfg.AWS_PROFILE; Set-State 'awsRegion' $cfg.AWS_REGION; Set-State 'azLocation' $cfg.AZ_LOCATION
    Set-State 'resourceGroup' $Names.Rg; Set-State 'foundry' $Names.Foundry; Set-State 'domainPrefix' $Names.DomainPrefix
}

function Test-Prerequisites {
    Write-Step 'Prerequisites'
    Assert-Command dotnet 'install the .NET 10 SDK'
    if (-not ((& dotnet --list-sdks) -match '^10\.')) { Stop-Setup '.NET 10 SDK not found (dotnet --list-sdks).' }
    Assert-Command node 'install Node.js'; Assert-Command npx 'install Node.js (npx)'; Assert-Command aws 'install AWS CLI v2'
    if (Test-Level 'local-foundry') { Assert-Command az 'install Azure CLI' }
    & npx @Cdk --version *> $null
    if ($LASTEXITCODE -ne 0) { Stop-Setup 'AWS CDK CLI not available through npx.' }
    Write-Info "dotnet 10, node, aws$(if (Test-Level 'local-foundry') { ', az' }), cdk: ok"

    if ($DryRun) {
        Write-Info 'dry-run: AWS/Azure login checks skipped (no cloud calls)'
        $script:Account = '<aws-account-id>'
    } else {
        $script:Account = (& aws sts get-caller-identity --query Account --output text 2>$null | Out-String).Trim()
        if ($LASTEXITCODE -ne 0 -or -not $script:Account) {
            Stop-Setup "AWS session for profile '$($cfg.AWS_PROFILE)' missing or expired: run 'aws login --profile $($cfg.AWS_PROFILE)' (or 'aws sso login --profile $($cfg.AWS_PROFILE)'), then retry."
        }
        if (Test-Level 'local-foundry') {
            & az account get-access-token --query expiresOn -o tsv *> $null
            if ($LASTEXITCODE -ne 0) { Stop-Setup "Azure session missing or expired: run 'az login', then retry." }
        }
        Write-Info 'AWS and Azure sessions: ok'
    }

    $bound = [string](Read-JsonFile $CdkContext)['domainPrefix']
    if ($bound -and $bound -ne $Names.DomainPrefix) {
        $msg = "infra/Commonroom.Infra/cdk.context.json already holds domainPrefix=${bound}: this checkout is bound to another Cognito deployment. Use a separate clone (or move that file away)."
        if ($DryRun) { Write-Info "WARNING (a real run stops here): $msg" } else { Stop-Setup $msg }
    }
}

# ---------------------------------------------------------------- steps
function Invoke-CognitoStep {
    Write-Step "a. Cognito ($Stack, domain prefix $($Names.DomainPrefix), $($cfg.AWS_REGION))"
    if ((Get-State 'cognitoDone') -eq '1') {
        Write-Info 'already deployed by this setup, skipped'
    } else {
        if (-not $DryRun) {
            & aws cloudformation describe-stacks --stack-name $Stack *> $null
            if ($LASTEXITCODE -eq 0) { Stop-Setup "Stack $Stack already exists in account/region and was not created by this setup: use another AWS account or region." }
        }
        $bootstrap = $true
        if ($DryRun) { Write-Info '(only if the CDKToolkit stack is missing)' }
        else { & aws cloudformation describe-stacks --stack-name CDKToolkit *> $null; $bootstrap = ($LASTEXITCODE -ne 0) }
        if ($bootstrap) { Invoke-Native 'npx' ($Cdk + @('bootstrap', "aws://$script:Account/$($cfg.AWS_REGION)")) $Infra }
        Set-CdkContext 'domainPrefix' $Names.DomainPrefix
        Invoke-Native 'npx' ($Cdk + @('deploy', $Stack, '--require-approval', 'never')) $Infra
        Set-State 'cognitoDone' '1'
    }
    $placeholder = "UserPoolId`t<UserPoolId>`nHostedUiDomain`thttps://<domain-prefix>.auth.<region>.amazoncognito.com`nClientIdProjectAlpha`t<ClientIdProjectAlpha>"
    $outputs = Get-NativeOutput $placeholder 'aws' @('cloudformation', 'describe-stacks', '--stack-name', $Stack,
        '--query', 'Stacks[0].Outputs[].[OutputKey,OutputValue]', '--output', 'text')
    $map = @{}
    foreach ($line in ($outputs -split "`r?`n")) { $p = $line -split "`t"; if ($p.Count -ge 2) { $map[$p[0]] = $p[1].Trim() } }
    $script:PoolId = $map['UserPoolId']; $script:HostedUi = $map['HostedUiDomain']; $script:ClientId = $map['ClientIdProjectAlpha']
    if (-not ($PoolId -and $HostedUi -and $ClientId)) { Stop-Setup "Could not read the $Stack outputs." }
    Set-State 'userPoolId' $PoolId
}

function Read-Password {
    while ($true) {
        $p1 = [System.Net.NetworkCredential]::new('', (Read-Host -AsSecureString '   Password (min 12 chars, upper, lower, digit)')).Password
        $p2 = [System.Net.NetworkCredential]::new('', (Read-Host -AsSecureString '   Repeat password')).Password
        if ($p1 -cne $p2) { Write-Info 'Passwords differ, retry.'; continue }
        if ($p1.Length -lt 12 -or $p1 -cnotmatch '[a-z]' -or $p1 -cnotmatch '[A-Z]' -or $p1 -notmatch '[0-9]') {
            Write-Info 'The password does not meet the pool policy, retry.'; continue
        }
        return $p1
    }
}

function Invoke-UserStep {
    Write-Step 'b. First user'
    $script:UserEmail = Get-State 'userEmail'
    if ($UserEmail) { Write-Info "user $UserEmail already created, skipped"; return }
    if ($DryRun) {
        $script:UserEmail = '<email>'; $pw = '<password>'
        Write-Info 'dry-run: email and password prompts skipped'
    } else {
        $script:UserEmail = (Read-Host '   Email of the first user').Trim()
        if ($UserEmail -notmatch '^[^@\s]+@[^@\s]+\.[^@\s]+$') { Stop-Setup 'Invalid email.' }
        $pw = Read-Password
    }
    $script:Secrets.Add($pw)
    $exists = $false
    if (-not $DryRun) {
        & aws cognito-idp admin-get-user --user-pool-id $PoolId --username $UserEmail *> $null
        $exists = ($LASTEXITCODE -eq 0)
    }
    if ($exists) { Write-Info 'user already exists in the pool: setting the password only' }
    else {
        Invoke-Native 'aws' @('cognito-idp', 'admin-create-user', '--user-pool-id', $PoolId, '--username', $UserEmail,
            '--user-attributes', "Name=email,Value=$UserEmail", 'Name=email_verified,Value=true',
            '--message-action', 'SUPPRESS', '--query', 'User.UserStatus', '--output', 'text')
    }
    Invoke-Native 'aws' @('cognito-idp', 'admin-set-user-password', '--user-pool-id', $PoolId, '--username', $UserEmail,
        '--password', $pw, '--permanent')
    Invoke-Native 'aws' @('cognito-idp', 'admin-add-user-to-group', '--user-pool-id', $PoolId, '--username', $UserEmail,
        '--group-name', 'members')
    $pw = $null
    Set-State 'userEmail' $UserEmail
}

function Invoke-ApiKeyStep {
    Write-Step 'c. API key'
    $existing = Get-DotEnvValue (Join-Path $HostDir '.env.local') 'VITE_API_KEY'
    if ((Get-State 'apiKeyDone') -eq '1' -and $existing -and $existing -ne '<api-key>') {
        $script:ApiKey = $existing
        Write-Info 'reusing the key already in apps/demo-host/.env.local'
    } else {
        $script:ApiKey = [Convert]::ToBase64String([byte[]](New-RandomString 32)).TrimEnd('=').Replace('+', '-').Replace('/', '_')
        Write-Info 'new random key (32 bytes, base64url): kept only in user-secrets and apps/demo-host/.env*.local'
    }
    $script:Secrets.Add($ApiKey)
}

function Set-UserSecret([string]$Key, [string]$Value) {
    Write-Host ('   + ' + (Get-Masked "dotnet user-secrets set `"$Key`" `"$Value`" --project backends/Commonroom.ReferenceApi"))
    if ($DryRun) { return }
    & dotnet user-secrets set $Key $Value --project $Backend *> $null
    if ($LASTEXITCODE -ne 0) { Stop-Setup "dotnet user-secrets set $Key failed." }
}

function Write-LocalConfig([string]$Engine) {
    Write-Step "d. Local configuration (Chat:Engine=$Engine)"
    $current = @{}
    foreach ($l in (& dotnet user-secrets list --project $Backend 2>$null)) {
        $p = $l -split ' = ', 2
        if ($p.Count -eq 2) { $current[$p[0].Trim()] = $p[1].Trim() }
    }
    $conflicts = @()
    if ($current['Cognito:UserPoolId'] -and $current['Cognito:UserPoolId'] -ne $PoolId) { $conflicts += 'another user pool' }
    if ($Engine -eq 'Foundry' -and $current['Foundry:ProjectEndpoint'] -and $current['Foundry:ProjectEndpoint'] -ne $FoundryEndpoint) {
        $conflicts += 'another Foundry project'
    }
    if ($conflicts) {
        $what = $conflicts -join ' and '
        if ($DryRun) { Write-Info "WARNING: the backend user-secrets point to $what; a real run asks before overwriting them" }
        else {
            $answer = Read-Host "   The backend user-secrets point to $what. Overwrite them? [y/N]"
            if ($answer -notin 'y', 'Y') { Stop-Setup 'Stopped: user-secrets left unchanged.' }
        }
    }
    Set-UserSecret 'Cognito:Region' $cfg.AWS_REGION
    Set-UserSecret 'Cognito:UserPoolId' $PoolId
    Set-UserSecret 'Cognito:ClientId' $ClientId
    Set-UserSecret 'ApiKeys:Allowed:0' $ApiKey
    Set-UserSecret 'Cors:AllowedOrigins:0' 'http://localhost:5173'
    Set-UserSecret 'Chat:Engine' $Engine
    if ($Engine -eq 'Foundry') {
        Set-UserSecret 'Foundry:ProjectEndpoint' $FoundryEndpoint
        Set-UserSecret 'Foundry:ModelDeployment' $Deployment
        Set-UserSecret 'VectorStores:Allowed:0' $VsId
    }
    Write-EnvFile (Join-Path $HostDir '.env.local') @(
        "VITE_OIDC_AUTHORITY=https://cognito-idp.$($cfg.AWS_REGION).amazonaws.com/$PoolId"
        "VITE_OIDC_CLIENT_ID=$ClientId"
        'VITE_OIDC_REDIRECT_URI=http://localhost:5173/callback'
        "VITE_COGNITO_DOMAIN=$HostedUi"
        'VITE_LOGOUT_URI=http://localhost:5173/'
        'VITE_API_BASE=http://localhost:5080'
        "VITE_API_KEY=$ApiKey"
        "VITE_VECTOR_STORE_ID=$VsId"
    )
    Set-State 'apiKeyDone' '1'
}

function Invoke-FoundryStep {
    $rg = $Names.Rg; $foundry = $Names.Foundry; $loc = $cfg.AZ_LOCATION
    Write-Step "e. Azure Foundry ($foundry in $loc) + vector store"
    Invoke-Once 'rgDone' 'az' @('group', 'create', '-n', $rg, '-l', $loc, '--output', 'none')
    Invoke-Once 'foundryDone' 'az' @('cognitiveservices', 'account', 'create', '-n', $foundry, '-g', $rg, '-l', $loc,
        '--kind', 'AIServices', '--sku', 'S0', '--custom-domain', $foundry, '--allow-project-management', '--assign-identity', '--yes', '--output', 'none')
    Invoke-Once 'projectDone' 'az' @('cognitiveservices', 'account', 'project', 'create', '-n', $foundry, '-g', $rg, '-l', $loc,
        '--project-name', $Project, '--output', 'none')
    Invoke-Once 'modelDone' 'az' @('cognitiveservices', 'account', 'deployment', 'create', '-n', $foundry, '-g', $rg,
        '--deployment-name', $Deployment, '--model-name', $cfg.MODEL_NAME, '--model-version', $cfg.MODEL_VERSION,
        '--model-format', 'OpenAI', '--sku-name', $cfg.MODEL_SKU, '--sku-capacity', $ModelCapacity, '--output', 'none')
    $script:FoundryEndpoint = "https://$foundry.services.ai.azure.com/api/projects/$Project"
    Set-State 'foundryEndpoint' $FoundryEndpoint

    $script:FoundryId = Get-NativeOutput "/subscriptions/<subscription-id>/resourceGroups/$rg/providers/Microsoft.CognitiveServices/accounts/$foundry" 'az' @(
        'cognitiveservices', 'account', 'show', '-n', $foundry, '-g', $rg, '--query', 'id', '-o', 'tsv')
    if ((Get-State 'roleUserDone') -ne '1') {
        $me = Get-NativeOutput '<signed-in-user-object-id>' 'az' @('ad', 'signed-in-user', 'show', '--query', 'id', '-o', 'tsv')
        Invoke-Once 'roleUserDone' 'az' @('role', 'assignment', 'create', '--role', 'Foundry User', '--scope', $FoundryId,
            '--assignee-object-id', $me, '--assignee-principal-type', 'User', '--output', 'none')
    }

    $script:VsId = Get-State 'vectorStoreId'
    if ($VsId) { Write-Info "vector store $VsId already created, skipped"; return }
    if (-not (Test-Path $cfg.DOCS_DIR -PathType Container)) { Stop-Setup "DOCS_DIR not found: $($cfg.DOCS_DIR)" }
    $docs = [IO.Path]::GetRelativePath($Repo, $cfg.DOCS_DIR)
    Write-Host "   + `$env:FOUNDRY_PROJECT_ENDPOINT='$FoundryEndpoint'; dotnet run --project tools/Commonroom.VectorSeed -- $docs commonroom-$($cfg.PREFIX)"
    if ($DryRun) { $script:VsId = '<vs_...>'; return }
    $env:FOUNDRY_PROJECT_ENDPOINT = $FoundryEndpoint
    try {
        foreach ($attempt in 1..5) {
            $out = (& dotnet run --project $Seed -- $cfg.DOCS_DIR "commonroom-$($cfg.PREFIX)" 2>&1 | Out-String)
            if ($LASTEXITCODE -eq 0 -and $out -match 'vector_store_id=(vs_[A-Za-z0-9_]+)') { $script:VsId = $Matches[1]; break }
            Write-Info "attempt $attempt failed (role assignments can take a few minutes):"
            ($out.Trim() -split "`r?`n" | Select-Object -Last 3) | ForEach-Object { Write-Info "  $_" }
            if ($attempt -lt 5) { Start-Sleep -Seconds 30 }
        }
    } finally { Remove-Item Env:FOUNDRY_PROJECT_ENDPOINT -ErrorAction SilentlyContinue }
    if (-not $VsId) { Stop-Setup 'Vector store creation failed.' }
    Set-State 'vectorStoreId' $VsId
    Write-Info "vector store: $VsId"
}

function Invoke-AzureStep {
    $rg = $Names.Rg; $api = $Names.Api; $swa = $Names.Swa; $plan = $Names.Plan; $loc = $cfg.AZ_LOCATION
    Write-Step "f. Azure App Service ($api) + Static Web App ($swa)"
    Invoke-Once 'planDone' 'az' @('appservice', 'plan', 'create', '-n', $plan, '-g', $rg, '-l', $loc, '--is-linux', '--sku', 'F1', '--output', 'none')
    Invoke-Once 'webappDone' 'az' @('webapp', 'create', '-n', $api, '-g', $rg, '-p', $plan, '--runtime', 'DOTNETCORE:10.0',
        '--https-only', 'true', '--min-tls-version', '1.2', '--startup-file', 'dotnet Commonroom.ReferenceApi.dll', '--output', 'none')
    Invoke-Once 'webappConfigDone' 'az' @('webapp', 'config', 'set', '-n', $api, '-g', $rg, '--ftps-state', 'Disabled', '--output', 'none')

    $principal = Get-State 'apiPrincipalId'
    if (-not $principal) {
        $principal = Get-NativeOutput '<api-principal-id>' 'az' @('webapp', 'identity', 'assign', '-n', $api, '-g', $rg, '--query', 'principalId', '-o', 'tsv')
        if (-not $DryRun) { Set-State 'apiPrincipalId' $principal }
    }
    Invoke-Once 'roleApiDone' 'az' @('role', 'assignment', 'create', '--role', 'Foundry User', '--scope', $FoundryId,
        '--assignee-object-id', $principal, '--assignee-principal-type', 'ServicePrincipal', '--output', 'none')

    Invoke-Once 'swaDone' 'az' @('staticwebapp', 'create', '-n', $swa, '-g', $rg, '-l', $cfg.AZ_SWA_LOCATION, '--sku', 'Free', '--output', 'none')
    $script:SwaHost = Get-NativeOutput '<swa-hostname>' 'az' @('staticwebapp', 'show', '-n', $swa, '-g', $rg, '--query', 'defaultHostname', '-o', 'tsv')
    $script:ApiUrl = "https://$api.azurewebsites.net"
    Set-State 'apiUrl' $ApiUrl; Set-State 'swaHost' $SwaHost

    Invoke-Native 'az' @('webapp', 'config', 'appsettings', 'set', '-n', $api, '-g', $rg, '--output', 'none', '--settings',
        'ASPNETCORE_ENVIRONMENT=Production', 'Chat__Engine=Foundry',
        "Foundry__ProjectEndpoint=$FoundryEndpoint", "Foundry__ModelDeployment=$Deployment",
        'Foundry__MaxOutputTokens=600', 'RateLimit__MessagesPerHour=20', "VectorStores__Allowed__0=$VsId",
        "Cognito__Region=$($cfg.AWS_REGION)", "Cognito__UserPoolId=$PoolId", "Cognito__ClientId=$ClientId",
        "ApiKeys__Allowed__0=$ApiKey", "Cors__AllowedOrigins__0=https://$SwaHost",
        'ConnectionStrings__Chat=Data Source=/home/data/commonroom.db')

    $work = Join-Path ([IO.Path]::GetTempPath()) "commonroom-setup-$([guid]::NewGuid().ToString('N'))"
    $script:TempPaths.Add($work)
    if (-not $DryRun) { New-Item -ItemType Directory -Path $work | Out-Null }
    Invoke-Native 'dotnet' @('publish', $Backend, '-c', 'Release', '-o', (Join-Path $work 'api'), '--nologo', '-v', 'q')
    New-ZipFile (Join-Path $work 'api') (Join-Path $work 'api.zip')
    Invoke-Native 'az' @('webapp', 'deploy', '-n', $api, '-g', $rg, '--src-path', (Join-Path $work 'api.zip'), '--type', 'zip', '--output', 'none')

    Write-EnvFile (Join-Path $HostDir '.env.production.local') @(
        "VITE_OIDC_AUTHORITY=https://cognito-idp.$($cfg.AWS_REGION).amazonaws.com/$PoolId"
        "VITE_OIDC_CLIENT_ID=$ClientId"
        "VITE_OIDC_REDIRECT_URI=https://$SwaHost/callback"
        "VITE_COGNITO_DOMAIN=$HostedUi"
        "VITE_LOGOUT_URI=https://$SwaHost/"
        "VITE_API_BASE=$ApiUrl"
        "VITE_API_KEY=$ApiKey"
        "VITE_VECTOR_STORE_ID=$VsId"
    )
    Invoke-Native 'npm' @('install', '--no-audit', '--no-fund') $Repo
    Invoke-Native 'npm' @('run', 'build') $Repo

    Write-Host "   + `$env:SWA_CLI_DEPLOYMENT_TOKEN = az staticwebapp secrets list -n $swa -g $rg --query properties.apiKey -o tsv"
    if (-not $DryRun) {
        $token = (& az staticwebapp secrets list -n $swa -g $rg --query properties.apiKey -o tsv | Out-String).Trim()
        if ($LASTEXITCODE -ne 0 -or -not $token) { Stop-Setup 'Could not read the Static Web App deployment token.' }
        $script:Secrets.Add($token)
        $env:SWA_CLI_DEPLOYMENT_TOKEN = $token
    }
    try { Invoke-Native 'npx' ($SwaCli + @('deploy', './dist', '--env', 'production')) $HostDir }
    finally { Remove-Item Env:SWA_CLI_DEPLOYMENT_TOKEN -ErrorAction SilentlyContinue }

    Write-Step 'f. Cognito: allow the Static Web App URLs'
    Set-CdkContext 'callbackUrls:project-alpha' "https://$SwaHost/callback"
    Set-CdkContext 'logoutUrls:project-alpha' "https://$SwaHost/"
    Invoke-Native 'npx' ($Cdk + @('deploy', $Stack, '--require-approval', 'never')) $Infra
}

function Write-Summary {
    Write-Step "Done (LEVEL=$($cfg.LEVEL), PREFIX=$($cfg.PREFIX))"
    Write-Info "Cognito Hosted UI : $HostedUi"
    Write-Info "First user        : $UserEmail (group members)"
    if (Test-Level 'local-foundry') {
        Write-Info "Foundry project   : $FoundryEndpoint"
        Write-Info "Vector store      : $VsId"
    }
    if (Test-Level 'azure') {
        Write-Info "API               : $ApiUrl  (health: $ApiUrl/health)"
        Write-Info "Demo site         : https://$SwaHost"
    }
    Write-Info ''
    Write-Info 'Run locally:'
    Write-Info '  dotnet run --project backends/Commonroom.ReferenceApi --urls http://localhost:5080'
    Write-Info '  npm install; npm run build -w @commonroom/chat-widget; npm run dev   # http://localhost:5173'
    Write-Info ''
    Write-Info 'Tear down: pwsh deploy/teardown.ps1'
    if ($DryRun) { Write-Info 'DRY RUN: nothing was executed, no file or secret was written.' }
}

