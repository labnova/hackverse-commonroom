#Requires -Version 7.0
<#
.SYNOPSIS
    Commonroom setup for LEVEL=local-fake | local-foundry | azure (see deploy/env.example).
.DESCRIPTION
    Re-runnable: progress and produced values are kept in deploy/.state.json (gitignored).
    -DryRun prints the commands without running them: no cloud calls, no files or secrets written.
.EXAMPLE
    pwsh deploy/setup.ps1 -DryRun
#>
