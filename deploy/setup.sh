#!/usr/bin/env bash
# Commonroom setup for LEVEL=local-fake | local-foundry | azure (see deploy/env.example).
# Usage: deploy/setup.sh [--dry-run]
# Re-runnable: progress and produced values are kept in deploy/.state.json (gitignored).
# --dry-run prints the commands without running them: no cloud calls, no files or secrets written.
set -euo pipefail

DRY_RUN=0
for arg in "$@"; do
  case "$arg" in
    --dry-run) DRY_RUN=1 ;;
    -h|--help) sed -n '2,5p' "$0"; exit 0 ;;
    *) echo "Unknown argument: $arg" >&2; exit 2 ;;
  esac
done

DEPLOY_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO="$(cd "$DEPLOY_DIR/.." && pwd)"
ENV_FILE="$DEPLOY_DIR/env.local"
STATE_FILE="$DEPLOY_DIR/.state.json"
INFRA="$REPO/infra/Commonroom.Infra"
CDK_CONTEXT="$INFRA/cdk.context.json"
BACKEND="$REPO/backends/Commonroom.ReferenceApi"
SEED="$REPO/tools/Commonroom.VectorSeed"
HOST_DIR="$REPO/apps/demo-host"
STACK=CommonroomAuthStack
PROJECT=commonroom
DEPLOYMENT=chat-mini
MODEL_CAPACITY=10
CDK=(npx --yes aws-cdk@2)
SWA_CLI=(npx --yes @azure/static-web-apps-cli)

# ---------------------------------------------------------------- helpers
SECRETS=()
log()  { printf '\n== %s\n' "$*"; }
info() { printf '   %s\n' "$*"; }
die()  { printf '\nERROR: %s\n' "$*" >&2; exit 1; }
mask() {
  local s="$*" x
  for x in "${SECRETS[@]+"${SECRETS[@]}"}"; do [[ -n "$x" ]] && s="${s//"$x"/***}"; done
  printf '%s' "$s"
}
show() { local s="$*"; s=${s/#az_scoped /az }; s=${s/#make_zip /zip }; printf '   + %s\n' "$(mask "$s")"; }
# run CMD...: print the command, run it unless --dry-run.
# quoted: arguments joined for display, those with spaces in double quotes.
quoted() { local a out=(); for a in "$@"; do [[ "$a" == *[[:space:]]* ]] && a="\"$a\""; out+=("$a"); done; printf "%s" "${out[*]}"; }
run() { show "$(quoted "$@")"; (( DRY_RUN )) && return 0; "$@"; }
# capture VAR PLACEHOLDER CMD...: stdout of CMD into VAR (PLACEHOLDER with --dry-run).
capture() {
  local __var=$1 __ph=$2 __out; shift 2
  show "$(quoted "$@")"
  if (( DRY_RUN )); then __out=$__ph; else __out=$("$@"); fi
  __out=${__out//$'\r'/}
  printf -v "$__var" '%s' "$__out"
}
# Git Bash rewrites arguments that start with '/' (e.g. /subscriptions/...): disable it for az scopes only.
az_scoped() { MSYS_NO_PATHCONV=1 az "$@"; }
# Native Windows tools (node) need Windows paths under Git Bash.
npath() { if command -v cygpath >/dev/null 2>&1; then cygpath -w "$1"; else printf '%s' "$1"; fi; }

json_get() { # FILE KEY
  node -e 'const fs=require("fs");let s={};try{s=JSON.parse(fs.readFileSync(process.argv[1],"utf8"))}catch(e){}
const v=s[process.argv[2]];process.stdout.write(v===undefined||v===null?"":String(v))' "$(npath "$1")" "$2"
}
json_set() { # FILE KEY VALUE
  node -e 'const fs=require("fs");const f=process.argv[1];let s={};try{s=JSON.parse(fs.readFileSync(f,"utf8"))}catch(e){}
s[process.argv[2]]=process.argv[3];fs.writeFileSync(f,JSON.stringify(s,null,2)+"\n")' "$(npath "$1")" "$2" "$3"
}
state_get() { json_get "$STATE" "$1"; }
state_set() { json_set "$STATE" "$1" "$2"; }
ctx_set() {
  show "set \"$1\": \"$2\" in infra/Commonroom.Infra/cdk.context.json"
  (( DRY_RUN )) && return 0
  json_set "$CDK_CONTEXT" "$1" "$2"
}
# once KEY CMD...: run CMD only if state KEY is not 1, then set it.
once() {
  local key=$1; shift
  if [[ "$(state_get "$key")" == 1 ]]; then show "$(quoted "$@")"; info "  (already done, skipped)"; return 0; fi
  run "$@"
  state_set "$key" 1
}
env_get() { # FILE KEY -> value of KEY=... in a dotenv file
  [[ -f "$1" ]] || return 0
  sed -n "s/^$2=//p" "$1" | tr -d '\r' | tail -n 1
}
write_env_file() { # FILE LINE...
  local file=$1 rel=${1#"$REPO"/} content; shift
  content=$(printf '%s\n' "# Generated by deploy/setup (LEVEL=$LEVEL). Do not commit." "$@")
  show "write $rel"
  for l in "$@"; do info "    $(mask "$l")"; done
  (( DRY_RUN )) && return 0
  if [[ -f "$file" ]] && [[ "$(cat "$file")" != "$content" ]]; then
    local bak; bak="$file.bak-$(date +%Y%m%d%H%M%S)"
    cp "$file" "$bak"; info "previous file kept as ${bak#"$REPO"/}"
  fi
  printf '%s\n' "$content" > "$file"
  git -C "$REPO" check-ignore -q "$file" || die "$rel is not git-ignored: stop before a key is committed."
}
make_zip() { # SRC_DIR ZIP_FILE (tar/bsdtar first; never GNU tar, which cannot write zip)
  local src=$1 out=$2 wintar=""
  if [[ -n "${SYSTEMROOT:-}" ]] && command -v cygpath >/dev/null 2>&1; then wintar="$(cygpath -u "$SYSTEMROOT")/System32/tar.exe"; fi
  if [[ -n "$wintar" && -x "$wintar" ]]; then "$wintar" -a -c -f "$(npath "$out")" -C "$(npath "$src")" .
  elif tar --version 2>/dev/null | grep -q bsdtar; then tar -a -c -f "$out" -C "$src" .
  elif command -v zip >/dev/null 2>&1; then (cd "$src" && zip -qr "$out" .)
  else die "No zip-capable tool found (bsdtar or zip)."; fi
}
need() { command -v "$1" >/dev/null 2>&1 || die "'$1' not found: $2"; }
level_at_least() { # local-fake < local-foundry < azure
  local order=(local-fake local-foundry azure) i want=-1 have=-1
  for i in "${!order[@]}"; do [[ ${order[$i]} == "$1" ]] && want=$i; [[ ${order[$i]} == "$LEVEL" ]] && have=$i; done
  (( have >= want ))
}

# ---------------------------------------------------------------- configuration
load_env() {
  [[ -f "$ENV_FILE" ]] || die "deploy/env.local not found: cp deploy/env.example deploy/env.local, then edit it."
  local line k v
  while IFS= read -r line || [[ -n "$line" ]]; do
    line=${line%$'\r'}; line=${line%%#*}
    [[ "$line" =~ ^[[:space:]]*([A-Z_][A-Z0-9_]*)[[:space:]]*=[[:space:]]*(.*)$ ]] || continue
    k=${BASH_REMATCH[1]}; v=${BASH_REMATCH[2]}; v=${v%"${v##*[![:space:]]}"}
    case "$k" in
      PREFIX|LEVEL|AWS_PROFILE|AWS_REGION|AZ_LOCATION|AZ_SWA_LOCATION|MODEL_NAME|MODEL_VERSION|MODEL_SKU|DOCS_DIR)
        printf -v "$k" '%s' "$v" ;;
    esac
  done < "$ENV_FILE"
  PREFIX=${PREFIX:-}; LEVEL=${LEVEL:-}; AWS_PROFILE=${AWS_PROFILE:-default}; AWS_REGION=${AWS_REGION:-}
  AZ_LOCATION=${AZ_LOCATION:-}; AZ_SWA_LOCATION=${AZ_SWA_LOCATION:-}; MODEL_NAME=${MODEL_NAME:-}
  MODEL_VERSION=${MODEL_VERSION:-}; MODEL_SKU=${MODEL_SKU:-}; DOCS_DIR=${DOCS_DIR:-samples/docs}

  [[ "$PREFIX" =~ ^[a-z][a-z0-9-]{1,14}[a-z0-9]$ ]] || die "PREFIX must be 3-16 chars: lowercase letters, digits, '-'."
  [[ "$PREFIX" =~ aws|amazon|cognito ]] && die "PREFIX must not contain aws, amazon or cognito (Cognito domain rule)."
  case "$LEVEL" in local-fake|local-foundry|azure) ;; *) die "LEVEL must be local-fake, local-foundry or azure." ;; esac
  [[ -n "$AWS_REGION" ]] || die "AWS_REGION is required."
  if level_at_least local-foundry; then
    local v2
    for v2 in AZ_LOCATION MODEL_NAME MODEL_VERSION MODEL_SKU; do [[ -n "${!v2}" ]] || die "$v2 is required for LEVEL=$LEVEL."; done
  fi
  if level_at_least azure; then [[ -n "$AZ_SWA_LOCATION" ]] || die "AZ_SWA_LOCATION is required for LEVEL=azure."; fi
  [[ "$DOCS_DIR" = /* ]] || DOCS_DIR="$REPO/$DOCS_DIR"
  export AWS_PROFILE AWS_REGION
  export CDK_DEFAULT_REGION="$AWS_REGION" AWS_DEFAULT_REGION="$AWS_REGION"
}

init_state() {
  if (( DRY_RUN )); then
    STATE=$(mktemp); TMP_DIRS+=("$STATE")
    if [[ -f "$STATE_FILE" ]]; then cp "$STATE_FILE" "$STATE"; else echo '{}' > "$STATE"; fi
  else
    STATE=$STATE_FILE
    [[ -f "$STATE" ]] || echo '{}' > "$STATE"
  fi
  local saved; saved=$(state_get prefix)
  [[ -z "$saved" || "$saved" == "$PREFIX" ]] || die "deploy/.state.json belongs to PREFIX=$saved: run deploy/teardown.sh first or restore that PREFIX."
  SUFFIX=$(state_get suffix)
  if [[ -z "$SUFFIX" ]]; then
    SUFFIX=$(node -e 'const c=require("crypto"),a="abcdefghijklmnopqrstuvwxyz0123456789";let s="";for(const b of c.randomBytes(4))s+=a[b%36];process.stdout.write(s)')
  fi
  RG="rg-$PREFIX-$SUFFIX"; FOUNDRY="foundry-$PREFIX-$SUFFIX"; PLAN="plan-$PREFIX-$SUFFIX"
  API="api-$PREFIX-$SUFFIX"; SWA="swa-$PREFIX-$SUFFIX"; DOMAIN_PREFIX="$PREFIX-$SUFFIX"
  state_set prefix "$PREFIX"; state_set suffix "$SUFFIX"; state_set level "$LEVEL"
  state_set awsProfile "$AWS_PROFILE"; state_set awsRegion "$AWS_REGION"; state_set azLocation "$AZ_LOCATION"
  state_set resourceGroup "$RG"; state_set foundry "$FOUNDRY"; state_set domainPrefix "$DOMAIN_PREFIX"
}

check_prereqs() {
  log "Prerequisites"
  need dotnet "install the .NET 10 SDK"
  dotnet --list-sdks 2>/dev/null | grep -q '^10\.' || die ".NET 10 SDK not found (dotnet --list-sdks)."
  need node "install Node.js"; need npx "install Node.js (npx)"; need aws "install AWS CLI v2"
  level_at_least local-foundry && need az "install Azure CLI"
  "${CDK[@]}" --version >/dev/null 2>&1 || die "AWS CDK CLI not available through npx."
  info "dotnet 10, node, aws$(level_at_least local-foundry && printf ', az'), cdk: ok"

  if (( DRY_RUN )); then
    info "dry-run: AWS/Azure login checks skipped (no cloud calls)"
    ACCOUNT='<aws-account-id>'
  else
    ACCOUNT=$(aws sts get-caller-identity --query Account --output text 2>/dev/null | tr -d '\r') \
      || die "AWS session for profile '$AWS_PROFILE' missing or expired: run 'aws login --profile $AWS_PROFILE' (or 'aws sso login --profile $AWS_PROFILE'), then retry."
    if level_at_least local-foundry; then
      az account get-access-token --query expiresOn -o tsv >/dev/null 2>&1 \
        || die "Azure session missing or expired: run 'az login', then retry."
    fi
    info "AWS and Azure sessions: ok"
  fi

  local bound; bound=$(json_get "$CDK_CONTEXT" domainPrefix)
  if [[ -n "$bound" && "$bound" != "$DOMAIN_PREFIX" ]]; then
    local msg="infra/Commonroom.Infra/cdk.context.json already holds domainPrefix=$bound: this checkout is bound to another Cognito deployment. Use a separate clone (or move that file away)."
    if (( DRY_RUN )); then info "WARNING (a real run stops here): $msg"; else die "$msg"; fi
  fi
}

# ---------------------------------------------------------------- steps
step_cognito() {
  log "a. Cognito ($STACK, domain prefix $DOMAIN_PREFIX, $AWS_REGION)"
  if [[ "$(state_get cognitoDone)" == 1 ]]; then
    info "already deployed by this setup, skipped"
  else
    if (( ! DRY_RUN )) && aws cloudformation describe-stacks --stack-name "$STACK" >/dev/null 2>&1; then
      die "Stack $STACK already exists in account/region and was not created by this setup: use another AWS account or region."
    fi
    if (( DRY_RUN )); then
      info "(only if the CDKToolkit stack is missing)"
      (cd "$INFRA" && run "${CDK[@]}" bootstrap "aws://$ACCOUNT/$AWS_REGION")
    elif ! aws cloudformation describe-stacks --stack-name CDKToolkit >/dev/null 2>&1; then
      (cd "$INFRA" && run "${CDK[@]}" bootstrap "aws://$ACCOUNT/$AWS_REGION")
    fi
    ctx_set domainPrefix "$DOMAIN_PREFIX"
    (cd "$INFRA" && run "${CDK[@]}" deploy "$STACK" --require-approval never)
    state_set cognitoDone 1
  fi
  local outputs
  capture outputs $'UserPoolId\t<UserPoolId>\nHostedUiDomain\thttps://<domain-prefix>.auth.<region>.amazoncognito.com\nClientIdProjectAlpha\t<ClientIdProjectAlpha>' \
    aws cloudformation describe-stacks --stack-name "$STACK" --query "Stacks[0].Outputs[].[OutputKey,OutputValue]" --output text
  POOL_ID=$(awk -F'\t' '$1=="UserPoolId"{print $2}' <<<"$outputs")
  HOSTED_UI=$(awk -F'\t' '$1=="HostedUiDomain"{print $2}' <<<"$outputs")
  CLIENT_ID=$(awk -F'\t' '$1=="ClientIdProjectAlpha"{print $2}' <<<"$outputs")
  [[ -n "$POOL_ID" && -n "$HOSTED_UI" && -n "$CLIENT_ID" ]] || die "Could not read the $STACK outputs."
  state_set userPoolId "$POOL_ID"
}

read_password() {
  local p2
  while :; do
    read -rsp "   Password (min 12 chars, upper, lower, digit): " PW; echo
    read -rsp "   Repeat password: " p2; echo
    if [[ "$PW" != "$p2" ]]; then echo "   Passwords differ, retry."; continue; fi
    if (( ${#PW} < 12 )) || ! [[ "$PW" =~ [a-z] && "$PW" =~ [A-Z] && "$PW" =~ [0-9] ]]; then
      echo "   The password does not meet the pool policy, retry."; continue
    fi
    break
  done
}

step_user() {
  log "b. First user"
  USER_EMAIL=$(state_get userEmail)
  if [[ -n "$USER_EMAIL" ]]; then info "user $USER_EMAIL already created, skipped"; return 0; fi
  PW=""
  if (( DRY_RUN )); then
    USER_EMAIL='<email>'; PW='<password>'; info "dry-run: email and password prompts skipped"
  else
    read -rp "   Email of the first user: " USER_EMAIL
    [[ "$USER_EMAIL" =~ ^[^@[:space:]]+@[^@[:space:]]+\.[^@[:space:]]+$ ]] || die "Invalid email."
    read_password
  fi
  SECRETS+=("$PW")
  if (( ! DRY_RUN )) && aws cognito-idp admin-get-user --user-pool-id "$POOL_ID" --username "$USER_EMAIL" >/dev/null 2>&1; then
    info "user already exists in the pool: setting the password only"
  else
    run aws cognito-idp admin-create-user --user-pool-id "$POOL_ID" --username "$USER_EMAIL" \
      --user-attributes Name=email,Value="$USER_EMAIL" Name=email_verified,Value=true \
      --message-action SUPPRESS --query User.UserStatus --output text
  fi
  run aws cognito-idp admin-set-user-password --user-pool-id "$POOL_ID" --username "$USER_EMAIL" --password "$PW" --permanent
  run aws cognito-idp admin-add-user-to-group --user-pool-id "$POOL_ID" --username "$USER_EMAIL" --group-name members
  PW=""
  state_set userEmail "$USER_EMAIL"
}

step_api_key() {
  log "c. API key"
  local existing; existing=$(env_get "$HOST_DIR/.env.local" VITE_API_KEY)
  if [[ "$(state_get apiKeyDone)" == 1 && -n "$existing" && "$existing" != "<api-key>" ]]; then
    API_KEY=$existing; info "reusing the key already in apps/demo-host/.env.local"
  else
    API_KEY=$(node -e 'process.stdout.write(require("crypto").randomBytes(32).toString("base64url"))')
    info "new random key (32 bytes, base64url): kept only in user-secrets and apps/demo-host/.env*.local"
  fi
  SECRETS+=("$API_KEY")
}

secret_set() {
  show "dotnet user-secrets set \"$1\" \"$2\" --project backends/Commonroom.ReferenceApi"
  (( DRY_RUN )) && return 0
  dotnet user-secrets set "$1" "$2" --project "$BACKEND" >/dev/null
}

write_local_config() { # ENGINE (Fake|Foundry)
  local engine=$1 secrets cur_pool cur_foundry conflict=""
  log "d. Local configuration (Chat:Engine=$engine)"
  secrets=$(dotnet user-secrets list --project "$BACKEND" 2>/dev/null | tr -d '\r' || true)
  cur_pool=$(awk -F' = ' '$1=="Cognito:UserPoolId"{print $2}' <<<"$secrets")
  cur_foundry=$(awk -F' = ' '$1=="Foundry:ProjectEndpoint"{print $2}' <<<"$secrets")
  [[ -n "$cur_pool" && "$cur_pool" != "$POOL_ID" ]] && conflict="another user pool"
  [[ "$engine" == Foundry && -n "$cur_foundry" && "$cur_foundry" != "$FOUNDRY_ENDPOINT" ]] && conflict="${conflict:+$conflict and }another Foundry project"
  if [[ -n "$conflict" ]]; then
    if (( DRY_RUN )); then
      info "WARNING: the backend user-secrets point to $conflict; a real run asks before overwriting them"
    else
      local answer
      read -rp "   The backend user-secrets point to $conflict. Overwrite them? [y/N] " answer
      [[ "$answer" == y || "$answer" == Y ]] || die "Stopped: user-secrets left unchanged."
    fi
  fi
  secret_set "Cognito:Region" "$AWS_REGION"
  secret_set "Cognito:UserPoolId" "$POOL_ID"
  secret_set "Cognito:ClientId" "$CLIENT_ID"
  secret_set "ApiKeys:Allowed:0" "$API_KEY"
  secret_set "Cors:AllowedOrigins:0" "http://localhost:5173"
  secret_set "Chat:Engine" "$engine"
  if [[ "$engine" == Foundry ]]; then
    secret_set "Foundry:ProjectEndpoint" "$FOUNDRY_ENDPOINT"
    secret_set "Foundry:ModelDeployment" "$DEPLOYMENT"
    secret_set "VectorStores:Allowed:0" "$VS_ID"
  fi
  write_env_file "$HOST_DIR/.env.local" \
    "VITE_OIDC_AUTHORITY=https://cognito-idp.$AWS_REGION.amazonaws.com/$POOL_ID" \
    "VITE_OIDC_CLIENT_ID=$CLIENT_ID" \
    "VITE_OIDC_REDIRECT_URI=http://localhost:5173/callback" \
    "VITE_COGNITO_DOMAIN=$HOSTED_UI" \
    "VITE_LOGOUT_URI=http://localhost:5173/" \
    "VITE_API_BASE=http://localhost:5080" \
    "VITE_API_KEY=$API_KEY" \
    "VITE_VECTOR_STORE_ID=${VS_ID:-}"
  state_set apiKeyDone 1
}

step_foundry() {
  log "e. Azure Foundry ($FOUNDRY in $AZ_LOCATION) + vector store"
  once rgDone az group create -n "$RG" -l "$AZ_LOCATION" --output none
  once foundryDone az cognitiveservices account create -n "$FOUNDRY" -g "$RG" -l "$AZ_LOCATION" \
    --kind AIServices --sku S0 --custom-domain "$FOUNDRY" --allow-project-management --assign-identity --yes --output none
  once projectDone az cognitiveservices account project create -n "$FOUNDRY" -g "$RG" -l "$AZ_LOCATION" \
    --project-name "$PROJECT" --output none
  once modelDone az cognitiveservices account deployment create -n "$FOUNDRY" -g "$RG" --deployment-name "$DEPLOYMENT" \
    --model-name "$MODEL_NAME" --model-version "$MODEL_VERSION" --model-format OpenAI \
    --sku-name "$MODEL_SKU" --sku-capacity "$MODEL_CAPACITY" --output none
  FOUNDRY_ENDPOINT="https://$FOUNDRY.services.ai.azure.com/api/projects/$PROJECT"
  state_set foundryEndpoint "$FOUNDRY_ENDPOINT"

  capture FOUNDRY_ID "/subscriptions/<subscription-id>/resourceGroups/$RG/providers/Microsoft.CognitiveServices/accounts/$FOUNDRY" \
    az cognitiveservices account show -n "$FOUNDRY" -g "$RG" --query id -o tsv
  if [[ "$(state_get roleUserDone)" != 1 ]]; then
    local me; capture me '<signed-in-user-object-id>' az ad signed-in-user show --query id -o tsv
    once roleUserDone az_scoped role assignment create --role "Foundry User" --scope "$FOUNDRY_ID" \
      --assignee-object-id "$me" --assignee-principal-type User --output none
  fi

  VS_ID=$(state_get vectorStoreId)
  if [[ -n "$VS_ID" ]]; then
    info "vector store $VS_ID already created, skipped"
  else
    [[ -d "$DOCS_DIR" ]] || die "DOCS_DIR not found: $DOCS_DIR"
    show "FOUNDRY_PROJECT_ENDPOINT=$FOUNDRY_ENDPOINT dotnet run --project tools/Commonroom.VectorSeed -- ${DOCS_DIR#"$REPO"/} commonroom-$PREFIX"
    if (( DRY_RUN )); then
      VS_ID='<vs_...>'
    else
      local attempt out
      for attempt in 1 2 3 4 5; do
        if out=$(FOUNDRY_PROJECT_ENDPOINT="$FOUNDRY_ENDPOINT" dotnet run --project "$SEED" -- "$DOCS_DIR" "commonroom-$PREFIX" 2>&1); then
          VS_ID=$(grep -o 'vector_store_id=vs_[A-Za-z0-9_]*' <<<"$out" | tail -n 1 | cut -d= -f2)
          [[ -n "$VS_ID" ]] && break
        fi
        info "attempt $attempt failed (role assignments can take a few minutes):"
        tail -n 3 <<<"$out" | sed 's/^/     /'
        (( attempt < 5 )) && sleep 30
      done
      [[ -n "$VS_ID" ]] || die "Vector store creation failed."
      state_set vectorStoreId "$VS_ID"
      info "vector store: $VS_ID"
    fi
  fi
}

step_azure() {
  log "f. Azure App Service ($API) + Static Web App ($SWA)"
  once planDone az appservice plan create -n "$PLAN" -g "$RG" -l "$AZ_LOCATION" --is-linux --sku F1 --output none
  once webappDone az webapp create -n "$API" -g "$RG" -p "$PLAN" --runtime "DOTNETCORE:10.0" \
    --https-only true --min-tls-version 1.2 --startup-file "dotnet Commonroom.ReferenceApi.dll" --output none
  once webappConfigDone az webapp config set -n "$API" -g "$RG" --ftps-state Disabled --output none

  local principal; principal=$(state_get apiPrincipalId)
  if [[ -z "$principal" ]]; then
    capture principal '<api-principal-id>' az webapp identity assign -n "$API" -g "$RG" --query principalId -o tsv
    (( DRY_RUN )) || state_set apiPrincipalId "$principal"
  fi
  once roleApiDone az_scoped role assignment create --role "Foundry User" --scope "$FOUNDRY_ID" \
    --assignee-object-id "$principal" --assignee-principal-type ServicePrincipal --output none

  once swaDone az staticwebapp create -n "$SWA" -g "$RG" -l "$AZ_SWA_LOCATION" --sku Free --output none
  capture SWA_HOST '<swa-hostname>' az staticwebapp show -n "$SWA" -g "$RG" --query defaultHostname -o tsv
  API_URL="https://$API.azurewebsites.net"
  state_set apiUrl "$API_URL"; state_set swaHost "$SWA_HOST"

  run az webapp config appsettings set -n "$API" -g "$RG" --output none --settings \
    ASPNETCORE_ENVIRONMENT=Production Chat__Engine=Foundry \
    "Foundry__ProjectEndpoint=$FOUNDRY_ENDPOINT" "Foundry__ModelDeployment=$DEPLOYMENT" \
    Foundry__MaxOutputTokens=600 RateLimit__MessagesPerHour=20 "VectorStores__Allowed__0=$VS_ID" \
    "Cognito__Region=$AWS_REGION" "Cognito__UserPoolId=$POOL_ID" "Cognito__ClientId=$CLIENT_ID" \
    "ApiKeys__Allowed__0=$API_KEY" "Cors__AllowedOrigins__0=https://$SWA_HOST" \
    "ConnectionStrings__Chat=Data Source=/home/data/commonroom.db"

  local work; work=$(mktemp -d); TMP_DIRS+=("$work")
  run dotnet publish "$BACKEND" -c Release -o "$work/api" --nologo -v q
  run make_zip "$work/api" "$work/api.zip"
  run az webapp deploy -n "$API" -g "$RG" --src-path "$work/api.zip" --type zip --output none

  write_env_file "$HOST_DIR/.env.production.local" \
    "VITE_OIDC_AUTHORITY=https://cognito-idp.$AWS_REGION.amazonaws.com/$POOL_ID" \
    "VITE_OIDC_CLIENT_ID=$CLIENT_ID" \
    "VITE_OIDC_REDIRECT_URI=https://$SWA_HOST/callback" \
    "VITE_COGNITO_DOMAIN=$HOSTED_UI" \
    "VITE_LOGOUT_URI=https://$SWA_HOST/" \
    "VITE_API_BASE=$API_URL" \
    "VITE_API_KEY=$API_KEY" \
    "VITE_VECTOR_STORE_ID=$VS_ID"
  (cd "$REPO" && run npm install --no-audit --no-fund && run npm run build)

  show "export SWA_CLI_DEPLOYMENT_TOKEN=\$(az staticwebapp secrets list -n $SWA -g $RG --query properties.apiKey -o tsv)"
  if (( ! DRY_RUN )); then
    SWA_CLI_DEPLOYMENT_TOKEN=$(az staticwebapp secrets list -n "$SWA" -g "$RG" --query properties.apiKey -o tsv | tr -d '\r')
    export SWA_CLI_DEPLOYMENT_TOKEN
    SECRETS+=("$SWA_CLI_DEPLOYMENT_TOKEN")
  fi
  (cd "$HOST_DIR" && run "${SWA_CLI[@]}" deploy ./dist --env production)
  unset SWA_CLI_DEPLOYMENT_TOKEN

  log "f. Cognito: allow the Static Web App URLs"
  ctx_set "callbackUrls:project-alpha" "https://$SWA_HOST/callback"
  ctx_set "logoutUrls:project-alpha" "https://$SWA_HOST/"
  (cd "$INFRA" && run "${CDK[@]}" deploy "$STACK" --require-approval never)
}

